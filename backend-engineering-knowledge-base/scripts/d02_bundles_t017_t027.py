def add_simple_topic(
    topics: dict,
    tid: str,
    title: str,
    slug: str,
    chain_dep: str,
    summary: str,
    mechanism: str,
    mermaid: str,
    code: str,
    code_file: str,
    complexities: str,
    ex1: str,
    ex2: str,
    ex3: str,
    sol_body: str,
    bullets: str,
    related: str,
):
    qa = mk_qa(title)
    interview_qs: list[str] = []
    for lvl, key in [
        ("Beginner", "Beginner"),
        ("Intermediate", "Intermediate"),
        ("Advanced", "Advanced"),
        ("Scenario", "Scenarios"),
        ("Follow-up", "Follow-ups"),
    ]:
        for q, _a in qa[key]:
            interview_qs.append(f"{lvl}. {q}")
    topics[tid] = std_sections(
        tid,
        title,
        slug,
        chain_dep,
        summary,
        mechanism,
        f"Execution path: validate input size n, allocate needed structures, single or multi-pass scan. {complexities} Backend services should cap n per request and stream large inputs.",
        mermaid,
        "Follow arrows for data movement; node IDs are camelCase without spaces.",
        f"Walk through a tiny hand example for {title}. Avoid mutating shared production arrays; copy slices in tests.",
        code_file,
        code,
        complexities + " Code unexecuted.",
        f"Apply {title} in rate limiting, log aggregation, batch ETL, and in-memory validation before persistence. Emit metrics on skipped work and reject oversize payloads with 413 or 400.",
        "| Pattern | Time | Space | Notes |\n| --- | --- | --- | --- |\n| Naive | O(n²) | O(1) | Baseline |\n| Optimized | See section B | See section B | Preferred |",
        f"- Forgetting edge cases (empty, one element).\n- Wrong invariant for {title}.\n- Ignoring overflow or timezone on time windows.",
        f"Reproduce with minimal input; log n and pointer indices; compare to brute force for small n.",
        qa,
        (ex1, ex2, ex3),
        sol_body,
        bullets,
        related,
        [
            f"Explain {title} invariant without notes.",
            f"Implement core routine and state complexity.",
            f"Debug a failing edge case.",
            f"Choose versus brute force for given n and q.",
        ],
        interview_qs,
    )


